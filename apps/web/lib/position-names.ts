function catalogKey(name: string) {
  return name
    .replace(/\s+/g, ' ')
    .replace(/\s*\(/g, ' (')
    .trim()
    .toLocaleLowerCase('ru');
}

function uniqueSortedNames(names: string[]) {
  const seen = new Set<string>();
  const unique: string[] = [];
  for (const raw of names) {
    const name = raw.replace(/\s+/g, ' ').replace(/\s*\(/g, ' (').trim();
    const key = catalogKey(name);
    if (!name || seen.has(key)) continue;
    seen.add(key);
    unique.push(name);
  }
  return unique.sort((a, b) => a.localeCompare(b, 'ru', { sensitivity: 'base' }));
}

export const POSITION_NAME_CATALOG = uniqueSortedNames(RAW_POSITION_NAMES);

/** Каталог + уже сохранённые в этапе названия, чтобы список не «терял» текущие положения. */
export function mergePositionNameCatalog(extra: Array<string | null | undefined> = []) {
  return uniqueSortedNames([...RAW_POSITION_NAMES, ...extra.filter((name): name is string => Boolean(name))]);
}
